import { describe, expect, it } from "vitest";
import { previewText } from "../src/lib/preview";

const LONG = 500;

describe("previewText: свойства заметки", () => {
	it("срезает блок свойств в начале файла", () => {
		expect(previewText("---\ntype: topic\n---\nТекст", LONG)).toBe("Текст");
	});

	it("не срезает, если закрывающей строки нет", () => {
		expect(previewText("---\nkey: value\nтекст", LONG)).toBe(
			"key: value\nтекст",
		);
	});

	it("не срезает, если файл начинается не с дефисов", () => {
		expect(previewText("Начало\n---\nkey: value\n---", LONG)).toBe(
			"Начало\n\nkey: value",
		);
	});

	it("возвращает пустую строку, если кроме свойств ничего нет", () => {
		expect(previewText("---\ntype: topic\n---", LONG)).toBe("");
	});

	it("возвращает пустую строку на пустом входе", () => {
		expect(previewText("", LONG)).toBe("");
	});
});

describe("previewText: разметка", () => {
	it("удаляет HTML-комментарии, в том числе многострочные", () => {
		expect(previewText("До <!-- скрыто\nещё --> после", LONG)).toBe(
			"До после",
		);
	});

	it("удаляет блок кода вместе с содержимым", () => {
		expect(previewText("До\n```js\nconst a = 1;\n```\nПосле", LONG)).toBe(
			"До\n\nПосле",
		);
	});

	it("снимает бэктики с инлайн-кода", () => {
		expect(previewText("Вызови `foo()` сейчас", LONG)).toBe(
			"Вызови foo() сейчас",
		);
	});

	it("удаляет изображения обоих видов", () => {
		expect(previewText("Вот ![alt](img.png) и ![[скрин.png]] конец", LONG)).toBe(
			"Вот и конец",
		);
	});

	it("разворачивает викиссылки в алиас или последний сегмент пути", () => {
		expect(previewText("Смотри [[папка/Заметка]] и [[путь/цель|алиас]]", LONG)).toBe(
			"Смотри Заметка и алиас",
		);
	});

	it("оставляет от обычной ссылки только текст", () => {
		expect(previewText("Ссылка [текст](https://a.b) тут", LONG)).toBe(
			"Ссылка текст тут",
		);
	});

	it("убирает решётки заголовков", () => {
		expect(previewText("# Заголовок\n## Второй", LONG)).toBe(
			"Заголовок\nВторой",
		);
	});

	it("убирает знаки цитаты, включая вложенную", () => {
		expect(previewText("> Цитата\n>> Вложенная", LONG)).toBe(
			"Цитата\nВложенная",
		);
	});

	it("убирает маркеры списков и чекбоксы", () => {
		const raw = "- Пункт\n* Второй\n+ Третий\n1. Четвёртый\n- [ ] Задача\n- [x] Готово";
		expect(previewText(raw, LONG)).toBe(
			"Пункт\nВторой\nТретий\nЧетвёртый\nЗадача\nГотово",
		);
	});

	it("снимает жирный, курсив, зачёркнутый и выделение", () => {
		const raw = "**жирный** __подчёркнутый__ *курсив* _наклон_ ~~вычерк~~ ==акцент==";
		expect(previewText(raw, LONG)).toBe(
			"жирный подчёркнутый курсив наклон вычерк акцент",
		);
	});

	it("удаляет горизонтальные линии", () => {
		expect(previewText("Текст\n---\n***\n___\nЕщё", LONG)).toBe("Текст\n\nЕщё");
	});
});

describe("previewText: пробелы", () => {
	it("схлопывает подряд идущие пробелы и табы в один", () => {
		expect(previewText("Заголовок \t  с    пробелами", LONG)).toBe(
			"Заголовок с пробелами",
		);
	});

	it("оставляет две пустые строки как есть", () => {
		expect(previewText("а\n\n\nб", LONG)).toBe("а\n\n\nб");
	});

	it("схлопывает три и более пустых строк в одну", () => {
		expect(previewText("а\n\n\n\n\nб", LONG)).toBe("а\n\nб");
	});

	it("обрезает пробелы по краям результата", () => {
		expect(previewText("\n\n  Текст  \n\n", LONG)).toBe("Текст");
	});
});

describe("previewText: обрезка", () => {
	it("не трогает текст короче лимита", () => {
		expect(previewText("Короткий", 100)).toBe("Короткий");
	});

	it("не трогает текст ровно по лимиту", () => {
		expect(previewText("абвгд", 5)).toBe("абвгд");
	});

	it("режет по границе слова, когда лимит попал на пробел", () => {
		expect(previewText("один два три четыре пять", 12)).toBe("один два три…");
	});

	it("режет по последней границе слова внутри лимита", () => {
		expect(previewText("один два три четыре пять", 14)).toBe("один два три…");
	});

	it("снимает хвостовые знаки препинания перед многоточием", () => {
		expect(previewText("Привет, мир и всё такое", 7)).toBe("Привет…");
	});

	it("режет жёстко, если пробела в пределах лимита нет", () => {
		expect(previewText("Длинноеслово", 5)).toBe("Длинн…");
	});

	it("возвращает пустую строку при лимите меньше единицы", () => {
		expect(previewText("любой текст", 0)).toBe("");
		expect(previewText("любой текст", -3)).toBe("");
	});

	// Содержимое вкладки Obsidian подставляет не сразу: пока файл не прочитан,
	// у представления вместо текста лежит null.
	it("возвращает пустую строку, когда текста ещё нет", () => {
		expect(previewText(null, LONG)).toBe("");
		expect(previewText(undefined, LONG)).toBe("");
	});
});
